"""d5tally.py - fill the TALLY-34 / TALLY-42 calibration rows from the Day-5 harvest,
and backfill RUN-MANIFEST with Day-4 and Day-5 rows (commission 2D + 3.7).

Tooling, not hand-edited prose (commission 2D). Idempotent: the generated block is
delimited and replaced wholesale on re-run, so G4 determinism holds.

Usage: python d5tally.py [--apply]      (default prints, --apply writes)
"""
import json, os, re, sys, glob, csv

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
ASIC = r"C:\dev\Claude\Projects\ASIC"
OUT = os.path.join(ASIC, "digest", "_verify", "d5run")
WMT = os.path.join(ASIC, "Web Model Tasks")
BEGIN = "<!-- D5-CALIBRATION-BEGIN -->"
END = "<!-- D5-CALIBRATION-END -->"

BLOCKS = {"red1": ("TALLY-34.md", "01", "RUNSHEET-34 Block 01 (BoomTile) - J-v1's own "
                                        "exemplar, declared known-IMPERFECT"),
          "red3": ("TALLY-42.md", "08", "RUNSHEET-42 Block 08 (Niagara) - J-v3's own "
                                        "exemplar, declared known-SOUND")}
FAM_PROMPT = {"e": "PROMPT-E-CALCULATIONS", "regz": "C1-REGZ-FACTOR",
              "strings": "C2-JCS-STRINGS", "red1": "J-ISSUE-REDTEAM-V1",
              "red3": "J-EPISODE-REDTEAM-V3",
              "alpha": "D2-ALPHA21264-RECALL", "niagara": "D2-NIAGARA-RECALL",
              "p4": "D2-PENTIUM4-RECALL", "pphysical": "D2-POWER4-PHYSICAL-RECALL",
              "lvs": "F-LVS-MISMATCH-CLASSES", "power": "D2-ALPHA21264-RECALL"}
DAY_DATE = {"Day 4": "2026-09-04", "Day 5": "2026-09-08"}


def calib_block(fam, harvest):
    tally, blk, desc = BLOCKS[fam]
    h = harvest[fam]
    g = {m: v for m, v in h.items() if v.get("gradable")}
    L = [BEGIN,
         "",
         f"## Calibration wave - Block {blk}, all {len(h)} Day-5 models "
         f"(generated by `digest/_verify/d5tally.py`, do not hand-edit)",
         "",
         f"Source: `Web Model Tasks/Day 5/* {fam}.json`. {desc}.",
         "",
         "**This wave measures reviewer calibration, not corpus quality** - every model",
         "reviewed the block that is baked into the prompt itself. `direction_check` is out",
         "of scope on a single-block wave and is deliberately absent rather than blank.",
         "",
         "| model | verdict | obj | fatal | major | minor | calibration | parse |",
         "|---|---|---|---|---|---|---|---|"]
    for m in sorted(g, key=lambda x: (g[x]["verdict_short"], x)):
        v = g[m]
        cal = v["calibration"].replace("MISCALIBRATED-bare-SOUND",
                                       "**MISCALIBRATED (bare SOUND)**")
        L.append(f"| {m} | {v['verdict_short']} | {v['objections']} | {v['fatal']} | "
                 f"{v['major']} | {v['minor']} | {cal} | {v['parse']} |")
    for m in sorted(h):
        if not h[m].get("gradable"):
            L.append(f"| {m} | NOT GRADABLE | — | — | — | — | parse failure | "
                     f"{h[m]['parse']} |")
    bare = sorted(m for m, v in g.items()
                  if v["calibration"].startswith("MISCALIBRATED"))
    anom = sorted((m, v["calibration"]) for m, v in g.items()
                  if v["calibration"].startswith("SCHEMA-ANOMALY"))
    L += ["",
          f"- **bare-SOUND ({len(bare)})**: {', '.join(bare) if bare else 'none'}. "
          f"The prompt's own BUILD NOTE declares this block "
          f"{'known-imperfect' if fam == 'red1' else 'known-sound-with-known-gaps'}, so a "
          f"SOUND verdict carrying zero objections is miscalibrated by the prompt's "
          f"definition, not by this digest's opinion.",
          f"- **schema anomalies ({len(anom)})**: "
          f"{', '.join(f'{m} ({c.split(chr(45))[-1]})' for m, c in anom) if anom else 'none'}"
          f" — a verdict inconsistent with the model's own objection list.",
          "", END]
    return "\n".join(L)


def splice(path, block):
    t = open(path, encoding="utf-8").read()
    if BEGIN in t and END in t:
        t = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), block, t, flags=re.S)
    else:
        t = t.rstrip() + "\n\n" + block + "\n"
    return t


def manifest_rows():
    rows = []
    for day in ("Day 4", "Day 5"):
        for p in sorted(glob.glob(os.path.join(WMT, day, "*.json"))):
            stem = os.path.basename(p)[:-5]
            if stem == "dispatch-state":
                continue
            fam = stem.rsplit(" ", 1)[-1]
            model = stem[: -(len(fam) + 1)]
            pid = FAM_PROMPT.get(fam, "UNMAPPED")
            rows.append((DAY_DATE[day], pid, model, os.path.basename(p)))
    return rows


def main():
    apply = "--apply" in sys.argv
    harvest = json.load(open(os.path.join(OUT, "d5redteam.json"), encoding="utf-8"))
    for fam, (tal, _, _) in BLOCKS.items():
        path = os.path.join(ASIC, "redteam", tal)
        new = splice(path, calib_block(fam, harvest))
        if apply:
            open(path, "w", encoding="utf-8", newline="").write(new)
        print(f"  {tal}: calibration block "
              f"{'WRITTEN' if apply else 'previewed'} "
              f"({len(harvest[fam])} models)")

    mpath = os.path.join(WMT, "RUN-MANIFEST.tsv")
    existing = set()
    with open(mpath, encoding="utf-8") as fh:
        rd = list(csv.reader(fh, delimiter="\t"))
    hdr, body = rd[0], rd[1:]
    for r in body:
        if len(r) >= 4:
            existing.add(r[3])
    new_rows = [r for r in manifest_rows() if r[3] not in existing]
    print(f"  RUN-MANIFEST: {len(body)} existing rows, {len(new_rows)} to append "
          f"-> {len(body) + len(new_rows)}")
    if apply and new_rows:
        with open(mpath, "a", encoding="utf-8", newline="") as fh:
            w = csv.writer(fh, delimiter="\t", lineterminator="\n")
            for r in new_rows:
                w.writerow(r)
        print(f"  RUN-MANIFEST: appended {len(new_rows)} rows")
    dual = [r for r in new_rows if r[2].startswith("minar")]
    print(f"  dual-spelling rows appended as collected: {[r[3] for r in dual]}")


if __name__ == "__main__":
    main()
